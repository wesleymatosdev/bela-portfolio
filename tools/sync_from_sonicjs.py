#!/usr/bin/env python3
"""Sync the SonicJS CMS content into this static repo (one-way publish).

Pulls published projects + media from the bela-sonicjs CMS and materializes
them into the site's static sources:

  - images  -> www/assets/media/<slug>-<n>.webp    (downloaded from the CMS's
               public /media/uploads/ route, then resized to webp derivatives —
               max 1600px, quality 85; SVGs pass through untouched. Skipped when
               the derivative already exists — idempotent. Originals are never
               committed: a 4096px PNG can weigh 10MB+, and the site modal
               shows images at ~680px wide)
  - content -> www/content/projects.json           (CMS is the source of truth;
               the list is replaced wholesale)
  - html    -> regenerated by tools/build_projects.py (run automatically)

Auth: the CMS credentials resolve in this order (first match wins):
  1. CMS_API_KEY env var  — an `sk_...` API key minted at
     /admin/plugins/api-keys (this is what CI uses, via a GitHub secret)
  2. 1Password            — the admin password via `op` (item
     "bela-sonicjs admin (SonicJS pilot)"), for local runs
The credentials are never printed or stored.

The site itself stays fully static: after sync, nothing references the CMS or
R2 at runtime. Review the diff, commit, and push — the Pages workflow rebuilds.

Usage: python3 tools/sync_from_sonicjs.py [--base URL]
"""

import json
import os
import subprocess
import sys
import time
import urllib.error
import urllib.request
from http.cookiejar import CookieJar
from pathlib import Path
from typing import NoReturn

CMS_BASE = "https://bela-sonicjs.wesleymatos.workers.dev"
OP_ITEM = "bela-sonicjs admin (SonicJS pilot)"
API_KEY = os.environ.get("CMS_API_KEY", "").strip()
ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "www" / "content" / "projects.json"
MEDIA = ROOT / "www" / "assets" / "media"
BUILD = ROOT / "tools" / "build_projects.py"

# webp derivative budget: the detail window shows media at ~680px (or 94vw
# maximized); 1600px covers retina comfortably while keeping files small.
MAX_DIM = 1600
WEBP_QUALITY = 85

TYPES = {".png": "png", ".jpg": "jpg", ".jpeg": "jpg", ".webp": "webp", ".svg": "svg"}


def die(msg) -> NoReturn:
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


def cms_password():
    r = subprocess.run(
        ["op", "read", f"op://Agent/{OP_ITEM}/password"],
        capture_output=True, text=True,
    )
    if r.returncode or not r.stdout.strip():
        die(f"could not read the CMS password from 1Password (`op`): {r.stderr.strip()[:200]}")
    return r.stdout.strip()


def sign_in(password):
    cj = CookieJar()
    opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(cj))
    req = urllib.request.Request(
        f"{CMS_BASE}/auth/sign-in/email", method="POST",
        data=json.dumps({"email": "admin@bela.local", "password": password}).encode(),
        headers={"Content-Type": "application/json", "Origin": CMS_BASE})
    try:
        opener.open(req, timeout=30)
    except urllib.error.HTTPError as e:
        die(f"CMS sign-in failed: HTTP {e.code}")
    return opener


def fetch_json(opener, path):
    headers = {"User-Agent": "bela-site-sync/1.0"}
    if API_KEY:
        headers["x-api-key"] = API_KEY
    req = urllib.request.Request(f"{CMS_BASE}{path}", headers=headers)
    with opener.open(req, timeout=60) as resp:
        return json.loads(resp.read().decode())


def fetch_bytes(opener, path, attempts=4) -> bytes:
    last = None
    for attempt in range(1, attempts + 1):
        try:
            req = urllib.request.Request(f"{CMS_BASE}{path}",
                                         headers={"User-Agent": "bela-site-sync/1.0"})
            with opener.open(req, timeout=90) as resp:
                return resp.read()
        except (urllib.error.URLError, urllib.error.HTTPError, TimeoutError, OSError) as e:
            last = e
            print(f"  download attempt {attempt}/{attempts} failed ({e}); retrying...")
            time.sleep(3 * attempt)
    die(f"download failed after {attempts} attempts: {path} ({last})")

def make_derivative(raw: bytes, dest: Path):
    """Resize + re-encode a downloaded original into the site's webp derivative.

    Transparency survives (RGBA); anything without alpha lands on RGB.
    Writes via a .part file so a crashed run never leaves a truncated image.
    """
    from io import BytesIO
    from PIL import Image, ImageOps

    img = Image.open(BytesIO(raw))
    img.load()
    img = ImageOps.exif_transpose(img)
    if img.mode == "P":
        img = img.convert("RGBA")
    if img.mode not in ("RGB", "RGBA"):
        img = img.convert("RGB")
    img.thumbnail((MAX_DIM, MAX_DIM), Image.Resampling.LANCZOS)
    tmp = dest.with_suffix(dest.suffix + ".part")
    img.save(tmp, "WEBP", quality=WEBP_QUALITY, method=4)
    tmp.replace(dest)


def main():
    api_key = os.environ.get("CMS_API_KEY", "").strip()
    if api_key:
        opener = urllib.request.build_opener()
        print("auth: CMS_API_KEY from environment")
    else:
        password = cms_password()
        opener = sign_in(password)
        print("auth: signed in via 1Password-sourced admin password")

    projects = fetch_json(opener, "/api/collections/projects/content?limit=100")["data"]
    media_rows = fetch_json(opener, "/api/documents?type=media_asset&status=published&limit=500")["data"]
    media = {m["id"]: m["data"].get("r2Key") for m in media_rows if m.get("data", {}).get("r2Key")}
    print(f"cms: {len(projects)} published projects, {len(media)} media assets")

    MEDIA.mkdir(parents=True, exist_ok=True)
    existing = json.loads(DATA.read_text(encoding="utf-8"))
    old_by_id = {p.get("id"): p for p in existing.get("projects", [])}

    site_projects, missing_years, downloaded = [], [], 0
    for i, it in enumerate(sorted(projects, key=lambda x: x["data"].get("sort") or 99), start=1):
        d = it["data"]
        slug = it["slug"] or f"project-{i}"
        media_ids = d.get("images") or ([d["coverImage"]] if d.get("coverImage") else [])
        images = []
        for n, mid in enumerate(media_ids, start=1):
            key = media.get(mid)
            if not key:
                die(f"project '{slug}': media id {mid} not found in the CMS media list")
            ext = "." + key.rsplit(".", 1)[-1].lower()
            if ext not in {f".{v}" for v in TYPES.values()}:
                die(f"project '{slug}': unsupported image extension for {key}")
            if ext == ".svg":
                # vector: ship as-is, nothing to resize
                fname = f"{slug}-{n}.svg"
                dest = MEDIA / fname
                if not dest.exists():
                    tmp = dest.with_suffix(dest.suffix + ".part")
                    tmp.write_bytes(fetch_bytes(opener, f"/media/{key}"))
                    tmp.replace(dest)
                    downloaded += 1
            else:
                # raster: store the resized webp derivative, never the original
                fname = f"{slug}-{n}.webp"
                dest = MEDIA / fname
                if not dest.exists():
                    make_derivative(fetch_bytes(opener, f"/media/{key}"), dest)
                    downloaded += 1
            images.append(fname)

        cms_year = d.get("year")
        old = old_by_id.get(slug) or old_by_id.get(it["id"])
        if cms_year:
            year = int(cms_year)
        elif old and old.get("year"):
            year = int(old["year"])
        else:
            year = 2026  # placeholder; flagged below so Bela can set the real year
            missing_years.append(slug)

        color = (d.get("color") or "").strip() or ""
        site_projects.append({
            "id": slug,
            "title": d.get("title") or slug,
            "blurb": d.get("blurb") or "",
            "year": year,
            "cat": d.get("category") or "brand",
            "color": color,  # empty = auto (palette-derived from the cover)
            "initials": d.get("initials") or slug[:2].upper(),
            "images": images,
        })

    DATA.write_text(json.dumps({"projects": site_projects}, indent=2, ensure_ascii=False) + "\n",
                    encoding="utf-8")
    print(f"synced {len(site_projects)} projects -> {DATA.relative_to(ROOT)} "
          f"({downloaded} new images downloaded)")

    orphans = sorted(f.name for f in MEDIA.iterdir()
                     if f.is_file() and not any(f.name in p["images"] for p in site_projects))
    if orphans:
        print(f"note: {len(orphans)} unreferenced files remain in www/assets/media "
              f"(left alone): {', '.join(orphans[:5])}{'...' if len(orphans) > 5 else ''}")

    r = subprocess.run([sys.executable, str(BUILD)], capture_output=True, text=True)
    sys.stdout.write(r.stdout)
    if r.returncode:
        sys.stderr.write(r.stderr)
        die("build_projects.py failed — projects.json written, fix the issue and re-run it")

    if missing_years:
        print(f"\nWARNING: {len(missing_years)} project(s) have no year in the CMS; "
              f"placeholder {2026} used — set the real year in the CMS and re-sync:")
        print("  " + ", ".join(missing_years))
    print("\nnext: review the diff, then commit + push to deploy (Pages rebuilds).")


if __name__ == "__main__":
    main()
